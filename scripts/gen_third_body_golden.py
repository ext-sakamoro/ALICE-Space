#!/usr/bin/env python3
"""Generate tests/golden/third_body.csv: the perturbing acceleration of a third
body on a satellite, a = -mu3 ((r - s)/|r - s|^3 + s/|s|^3), evaluated in
mpmath at 60 significant digits (r the satellite and s the body, both from
the central body's centre).

In f64 this difference of two nearly equal terms loses most of its digits
when |r| << |s| (a satellite near the Earth perturbed by the Sun); at 60
digits it does not, so the table is the reference an f64 formulation has to
meet. Every value is rounded once to the nearest f64.

Usage:
    python3 scripts/gen_third_body_golden.py           # write
    python3 scripts/gen_third_body_golden.py --check   # compare
"""

import pathlib
import sys

import mpmath

OUT = pathlib.Path(__file__).resolve().parent.parent / "tests" / "golden" / "third_body.csv"
mpmath.mp.dps = 60

# inputs of Sun- and Moon-like size (the field takes mu from the caller)
MU = {"sun": "132712440041.279419", "moon": "4902.800118"}
DIST = {"sun": "149597870.7", "moon": "384400"}


def cases():
    """Satellites from LEO to beyond the Moon's distance, in directions
    spread over the sphere, against the Sun and the Moon placed in spread
    directions."""
    out = []
    k = 0
    for body in ("sun", "moon"):
        for radius in ["6578", "7000", "26560", "42164", "100000", "300000"]:
            for j in range(12):
                k += 1
                th = mpmath.mpf(37 * k % 360) * mpmath.pi / 180
                ph = mpmath.mpf((53 * k) % 170 - 85) * mpmath.pi / 180
                tb = mpmath.mpf(71 * k % 360) * mpmath.pi / 180
                pb = mpmath.mpf((29 * k) % 50 - 25) * mpmath.pi / 180
                r = mpmath.mpf(radius)
                d = mpmath.mpf(DIST[body]) * (1 + mpmath.mpf(j) / 200)
                sat = (r * mpmath.cos(ph) * mpmath.cos(th), r * mpmath.cos(ph) * mpmath.sin(th), r * mpmath.sin(ph))
                s = (d * mpmath.cos(pb) * mpmath.cos(tb), d * mpmath.cos(pb) * mpmath.sin(tb), d * mpmath.sin(pb))
                out.append((body, [float(c) for c in sat], [float(c) for c in s]))
    return out


def accel(mu, r, s):
    r = [mpmath.mpf(c) for c in r]
    s = [mpmath.mpf(c) for c in s]
    d = [r[i] - s[i] for i in range(3)]
    nd = mpmath.sqrt(sum(c * c for c in d))
    ns = mpmath.sqrt(sum(c * c for c in s))
    return [-mu * (d[i] / nd ** 3 + s[i] / ns ** 3) for i in range(3)]


def main():
    lines = [
        "# generated by scripts/gen_third_body_golden.py (mpmath 60 digits, direct difference)",
        "body,mu,x,y,z,sx,sy,sz,ax,ay,az",
    ]
    for body, r, s in cases():
        mu = mpmath.mpf(MU[body])
        a = accel(mu, r, s)
        vals = [float(mu), *r, *s, *(float(c) for c in a)]
        lines.append(body + "," + ",".join(repr(v) for v in vals))
    text = "\n".join(lines) + "\n"
    if "--check" in sys.argv[1:]:
        if OUT.read_text(encoding="utf-8") != text:
            sys.exit(f"{OUT} differs from the regenerated table")
        print(f"{OUT.name}: {len(lines) - 2} rows match")
    else:
        OUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUT.name}: {len(lines) - 2} rows")


if __name__ == "__main__":
    main()
