#!/usr/bin/env python3
"""Generate tests/golden/zonal_gravity.csv: the potential and acceleration of
an axisymmetric (zonal) gravity field, U = (mu/r) (1 - sum_n Jn (R/r)^n Pn(z/r)),
evaluated in mpmath at 60 significant digits.

The acceleration is the gradient of U differentiated by mpmath itself
(numerical differentiation at 60 digits, `mpmath.diff`), not a closed-form
expression, so the expected values share no formula with src/gravity.rs. The
Legendre polynomials are mpmath's `legendre`. Every value is rounded once to
the nearest f64.

Usage:
    python3 scripts/gen_zonal_golden.py           # write
    python3 scripts/gen_zonal_golden.py --check   # compare
"""

import pathlib
import sys

import mpmath

OUT = pathlib.Path(__file__).resolve().parent.parent / "tests" / "golden" / "zonal_gravity.csv"
mpmath.mp.dps = 60

MU = mpmath.mpf("398600.4415")
R = mpmath.mpf("6378.1363")
# Three coefficient sets: J2 alone, J2..J6 of Earth-like size, and J2..J20
# with arbitrary values of decreasing size (signs alternate in blocks)
SETS = {
    "j2": ["1.0826e-3"],
    "j2-j6": ["1.0826e-3", "-2.5e-6", "-1.6e-6", "-2.3e-7", "5.4e-7"],
    "j2-j20": [f"{(-1) ** (k // 3) * (1.3 ** -k) * 1e-3:.6e}" for k in range(19)],
}


def positions():
    """Directions on a grid of latitude and longitude, the poles and the
    equator included, at radii from 1 to 10 times R."""
    out = []
    lats = [-90, -80, -45, -10, 0, 10, 30, 45, 80, 90]
    k = 0
    for lat in lats:
        for radius in ["1", "1.05", "1.6", "4.2", "10"]:
            lon = mpmath.mpf(37 * k % 360)
            phi = mpmath.radians(lat)
            lam = mpmath.radians(lon)
            r = mpmath.mpf(radius) * R
            out.append((r * mpmath.cos(phi) * mpmath.cos(lam), r * mpmath.cos(phi) * mpmath.sin(lam), r * mpmath.sin(phi)))
            k += 1
    return [tuple(float(c) for c in p) for p in out]


def potential(js, x, y, z):
    r = mpmath.sqrt(x * x + y * y + z * z)
    s = z / r
    total = mpmath.mpf(1)
    for n, j in enumerate(js, start=2):
        total -= mpmath.mpf(j) * (R / r) ** n * mpmath.legendre(n, s)
    return MU / r * total


def main():
    lines = [
        "# generated by scripts/gen_zonal_golden.py (mpmath 60 digits; acceleration = mpmath.diff of the potential)",
        "set,mu,radius,x,y,z,potential,ax,ay,az",
    ]
    for name, js in SETS.items():
        for x, y, z in positions():
            X, Y, Z = (mpmath.mpf(c) for c in (x, y, z))
            u = potential(js, X, Y, Z)
            ax = mpmath.diff(lambda t: potential(js, t, Y, Z), X)
            ay = mpmath.diff(lambda t: potential(js, X, t, Z), Y)
            az = mpmath.diff(lambda t: potential(js, X, Y, t), Z)
            vals = [float(MU), float(R), x, y, z, float(u), float(ax), float(ay), float(az)]
            lines.append(name + "," + ",".join(repr(v) for v in vals))
    lines.insert(1, "# sets: " + "; ".join(f"{k}={' '.join(v)}" for k, v in SETS.items()))
    text = "\n".join(lines) + "\n"
    if "--check" in sys.argv[1:]:
        if OUT.read_text(encoding="utf-8") != text:
            sys.exit(f"{OUT} differs from the regenerated table")
        print(f"{OUT.name}: {len(lines) - 3} rows match")
    else:
        OUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUT.name}: {len(lines) - 3} rows")


if __name__ == "__main__":
    main()
